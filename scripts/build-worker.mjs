import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const webRoot = join(root, 'web');
const outputRoot = join(root, 'dist');

const files = [
  ['/', 'index.html', 'text/html; charset=utf-8', 'no-cache'],
  ['/index.html', 'index.html', 'text/html; charset=utf-8', 'no-cache'],
  ['/styles.css', 'styles.css', 'text/css; charset=utf-8', 'public, max-age=3600'],
  ['/google-app.js', 'google-app.js', 'text/javascript; charset=utf-8', 'public, max-age=3600'],
  ['/favicon.svg', 'favicon.svg', 'image/svg+xml; charset=utf-8', 'public, max-age=86400'],
  ['/dados/assentamentos.json', 'dados/assentamentos.json', 'application/json; charset=utf-8', 'public, max-age=3600'],
  ['/dados/localidades.json', 'dados/localidades.json', 'application/json; charset=utf-8', 'public, max-age=3600'],
  ['/dados/metadados.json', 'dados/metadados.json', 'application/json; charset=utf-8', 'public, max-age=3600'],
  ['/geojson/abelardo-luz.geojson', 'geojson/abelardo-luz.geojson', 'application/geo+json; charset=utf-8', 'public, max-age=3600'],
  ['/geojson/assentamentos.geojson', 'geojson/assentamentos.geojson', 'application/geo+json; charset=utf-8', 'public, max-age=3600'],
];

const assetEntries = [];
for (const [route, source, contentType, cacheControl] of files) {
  const body = await readFile(join(webRoot, source), 'utf8');
  assetEntries.push([route, { body, contentType, cacheControl }]);
}

const generated = `// Generated by scripts/build-worker.mjs. Edit files in web/, not this file.
const assets = new Map(${JSON.stringify(assetEntries)});

function responseHeaders(asset) {
  return {
    'Content-Type': asset.contentType,
    'Cache-Control': asset.cacheControl,
    'X-Content-Type-Options': 'nosniff',
    'Referrer-Policy': 'strict-origin-when-cross-origin',
    'Permissions-Policy': 'geolocation=(), microphone=(), camera=()',
  };
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);

    if (url.pathname === '/config') {
      return Response.json(
        { googleMapsApiKey: env.GOOGLE_MAPS_API_KEY || '' },
        {
          headers: {
            'Cache-Control': 'no-store, max-age=0',
            'X-Content-Type-Options': 'nosniff',
          },
        },
      );
    }

    const asset = assets.get(url.pathname);
    if (!asset) {
      return new Response('Não encontrado', {
        status: 404,
        headers: { 'Content-Type': 'text/plain; charset=utf-8' },
      });
    }

    if (request.method === 'HEAD') {
      return new Response(null, { headers: responseHeaders(asset) });
    }

    if (request.method !== 'GET') {
      return new Response('Método não permitido', {
        status: 405,
        headers: { Allow: 'GET, HEAD', 'Content-Type': 'text/plain; charset=utf-8' },
      });
    }

    return new Response(asset.body, { headers: responseHeaders(asset) });
  },
};
`;

await mkdir(join(root, 'worker'), { recursive: true });
await mkdir(join(outputRoot, 'server'), { recursive: true });
await mkdir(join(outputRoot, '.openai'), { recursive: true });
await writeFile(join(root, 'worker', 'index.js'), generated, 'utf8');
await writeFile(join(outputRoot, 'server', 'index.js'), generated, 'utf8');
await writeFile(
  join(outputRoot, '.openai', 'hosting.json'),
  await readFile(join(root, '.openai', 'hosting.json'), 'utf8'),
  'utf8',
);

console.log(`Worker gerado com ${assetEntries.length} rotas estáticas.`);
